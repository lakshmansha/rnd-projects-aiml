"""Build content/PUBLISH_SHEET.md: paste-ready YouTube/Instagram text for the 18 long videos and 18 shorts.

    python tools/publish_sheet.py [--code-url URL] [--links links.json]

links.json (optional) maps project number -> {"long": "https://youtu.be/...", "short": "..."} and fills the {LONG_URL} / {SHORT_URL}
placeholders. Nothing is uploaded; this only writes text.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
C = ROOT / "content"
CODE_URL = "https://github.com/lakshmansha/rnd-projects-aiml"
if "--code-url" in sys.argv:
    CODE_URL = sys.argv[sys.argv.index("--code-url") + 1]
LINKS = {}
if "--links" in sys.argv:
    LINKS = json.loads(Path(sys.argv[sys.argv.index("--links") + 1]).read_text(encoding="utf-8"))


def section(md, *names):
    """Body of the first '## <name>' section (any of names, case-insensitive prefix), up to the next '## '."""
    for n in names:
        m = re.search(rf"^## {re.escape(n)}[^\n]*\n(.*?)(?=^## |\Z)", md, re.S | re.M | re.I)
        if m:
            return m.group(1).strip()
    return ""


def inline(md, label):
    m = re.search(rf"^\*\*{label}[^*\n]*\*\*:?\s*(.+)$", md, re.M | re.I)
    return m.group(1).strip() if m else ""


def meta(md):
    titles = [re.sub(r"^\d+\.\s*", "", l).strip() for l in section(md, "Titles", "Title options").splitlines() if re.match(r"^\d+\.", l)]
    thumb = inline(md, "Thumbnail text") or section(md, "Thumbnail text")
    tags = inline(md, "Tags") or section(md, "Tags")
    pinned = inline(md, "Pinned comment") or section(md, "Pinned comment")
    m = re.search(r"^\*\*Description:\*\*\s*\n(.*?)(?=^## |\Z)", md, re.S | re.M)
    desc = m.group(1).strip() if m else section(md, "Description")
    keep = [l for l in desc.splitlines() if not re.match(r"^(Chapters|Code|More builds)\s*:", l.strip(), re.I)
            and not re.match(r"^\d{1,2}:\d\d\s", l.strip())]  # old chapter lines; chapters.txt has the real timestamps
    return dict(titles=titles, thumb=re.sub(r"\s*\(alt:.*$", "", thumb).strip().strip('"'), tags=tags, pinned=pinned, desc="\n".join(keep).strip())


def shorts_plan():
    """{num: dict(day, title, yt_desc, ig)} from UPLOAD_PLAN.md."""
    t = (C / "UPLOAD_PLAN.md").read_text(encoding="utf-8")
    out = {}
    for m in re.finditer(r"^### Day (\d+): #(\d+) (.+?)\n(.*?)(?=^### Day |\Z)", t, re.S | re.M):
        day, num, title, body = int(m[1]), m[2], m[3].strip(), m[4]
        yt = re.search(r"YouTube description:\*\*\s*```\n(.*?)```", body, re.S)
        ig = re.search(r"Instagram caption:\*\*\s*```\n(.*?)```", body, re.S)
        out[num] = dict(day=day, title=title, yt=yt[1].strip() if yt else "", ig=ig[1].strip() if ig else "")
    return out


def add_line(text, line, before_hashtags=True):
    """Insert a line before the final hashtag/follow block."""
    parts = text.split("\n\n")
    if len(parts) >= 2 and ("#" in parts[-1] or parts[-1].startswith("Follow")):
        idx = len(parts) - 1
        if parts[-1].startswith("Follow") and len(parts) >= 3:
            idx = len(parts) - 2 if "#" in parts[-2] else len(parts) - 1
        parts.insert(max(1, idx if parts[-1].startswith("Follow") else idx), line)
        return "\n\n".join(parts)
    return text + "\n\n" + line


def main():
    plan = shorts_plan()
    nums = sorted(plan, key=lambda k: plan[k]["day"])
    lines = ["# Publish sheet: Watch It Learn", "",
             "Generated by `tools/publish_sheet.py` from each project's `full.md`, `chapters.txt` and `UPLOAD_PLAN.md`. Nothing here is uploaded automatically.", "",
             "## Order of work", "",
             "1. Upload the **18 long videos first** (section A) as **Unlisted**. Send me the 18 links (`links.json`, format below) and I fill them into the shorts.",
             "2. Post one short a day (section B) on **YouTube Shorts (Public)** and **Instagram Reels**, 7-9 PM India time. Each short points to its full video. When a short goes live, you can switch its full video from Unlisted to Public.",
             "3. Always tick the **AI-generated / altered content** disclosure (the narration is synthetic) and set **Not made for kids**.", "",
             "```json", '{"06": {"long": "https://youtu.be/XXXX"}, "09": {"long": "https://youtu.be/YYYY"}}', "```", "",
             "Placeholders: `{CODE_URL}` (public repo), `{LONG_URL}` (the full video), `{SHORT_URL}`.", "",
             "---", "", "# A. Long videos (upload as Unlisted)", ""]
    for num in nums:
        d = next(C.glob(f"{num}-*"))
        md = (d / "full.md").read_text(encoding="utf-8")
        m = meta(md)
        ch = (d / "chapters.txt").read_text(encoding="utf-8").strip()
        title = m["titles"][0] if m["titles"] else d.name
        desc = (m["desc"] + "\n\nChapters:\n" + ch + f"\n\nCode: {CODE_URL}\n"
                "Narration is AI-generated. Built with Claude Code (AI pair programmer).")
        lines += [f"## A{plan[num]['day']:02d}. #{num} {d.name[3:]}", "",
                  f"- File: `content/{d.name}/out/full.mp4`",
                  f"- Title ({len(title)} chars): `{title}`",
                  f"- Other title options: " + " / ".join(f"`{t}`" for t in m["titles"][1:]),
                  f"- Thumbnail text: {m['thumb']}",
                  "- Visibility: **Unlisted** now. AI-generated content: **Yes**. Made for kids: **No**. Category: Science & Technology.",
                  f"- Tags: {m['tags']}", "", "**Description:**", "", "```", desc, "```", "", "**Pinned comment** (post it after upload and pin it):", "", "```", m["pinned"], "```", ""]
    lines += ["---", "", "# B. Shorts (YouTube Shorts + Instagram Reels, one a day)", ""]
    for num in nums:
        p, d = plan[num], next(C.glob(f"{num}-*"))
        long_url = LINKS.get(num, {}).get("long", "{LONG_URL}")
        yt = add_line(p["yt"], f"Full walkthrough (code and chapters): {long_url}")
        ig = add_line(p["ig"], "Full video on YouTube: Watch It Learn (link in bio).")
        lines += [f"## B{p['day']:02d}. #{num} {p['title']}", "",
                  f"- File: `content/{d.name}/out/short_v2.mp4` (1080x1920)",
                  "- Post both on the same day. YouTube: Public + AI-generated content Yes + Not made for kids. Instagram: tick the AI label, cover frame = the result frame.", "",
                  "**YouTube title:**", "", f"`{p['title']}`", "", "**YouTube description:**", "", "```", yt, "```", "",
                  "**Instagram caption:**", "", "```", ig, "```", "",
                  "**Pinned comment (YouTube):** `Which project should I build next? The full walkthrough is linked in the description.`", ""]
    (C / "PUBLISH_SHEET.md").write_text("\n".join(lines), encoding="utf-8")
    print("wrote", C / "PUBLISH_SHEET.md", len(nums), "projects")


if __name__ == "__main__":
    main()
